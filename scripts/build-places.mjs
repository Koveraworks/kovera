#!/usr/bin/env node
// Reads src/data/places/source/places.json and generates:
//   src/data/places/states.js
//   src/data/places/districts/<CODE>.json
//   supabase/places.sql
// Usage: node scripts/build-places.mjs   (exits 1 on validation errors)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const srcFile = path.join(root, 'src/data/places/source/places.json')
const outDir = path.join(root, 'src/data/places')
const distDir = path.join(outDir, 'districts')
const sqlFile = path.join(root, 'supabase/places.sql')

const data = JSON.parse(fs.readFileSync(srcFile, 'utf8'))
const errors = []
const err = (m) => errors.push(m)
const DEVANAGARI = /[ऀ-ॿ]/
const norm = (s) => s.trim().toLowerCase()

if (!data.source || !data.retrieved) err('missing source/retrieved')
if (!Array.isArray(data.states) || !data.states.length) err('no states')

const codes = new Set()
const stateNames = new Set()
for (const s of data.states ?? []) {
  const tag = `state ${s.code ?? '?'} (${s.en ?? '?'})`
  if (!/^[A-Z]{2}$/.test(s.code ?? '')) err(`${tag}: bad code`)
  if (codes.has(s.code)) err(`${tag}: duplicate code`)
  codes.add(s.code)
  if (!s.en?.trim()) err(`${tag}: empty en`)
  if (stateNames.has(s.en)) err(`${tag}: duplicate state name`)
  stateNames.add(s.en)
  if (!s.hi?.trim() || !DEVANAGARI.test(s.hi)) err(`${tag}: hi missing or not Devanagari`)
  if (!Array.isArray(s.districts) || s.districts.length < 1) { err(`${tag}: no districts`); continue }
  const ens = new Set()
  for (const d of s.districts) {
    const dt = `${tag} / ${d.en ?? '?'}`
    if (!d.en?.trim()) { err(`${dt}: empty en`); continue }
    if (d.en !== d.en.trim()) err(`${dt}: en has surrounding whitespace`)
    if (ens.has(norm(d.en))) err(`${dt}: duplicate district en`)
    ens.add(norm(d.en))
    if (!d.hi?.trim()) err(`${dt}: empty hi`)
    else if (!DEVANAGARI.test(d.hi)) err(`${dt}: hi has no Devanagari`)
    if (!Array.isArray(d.aliases)) err(`${dt}: aliases must be an array`)
  }
  for (const d of s.districts) {
    const seen = new Set()
    for (const a of d.aliases ?? []) {
      if (!a?.trim()) err(`${tag} / ${d.en}: empty alias`)
      else if (ens.has(norm(a))) err(`${tag} / ${d.en}: alias "${a}" collides with a district name`)
      if (seen.has(norm(a ?? ''))) err(`${tag} / ${d.en}: duplicate alias "${a}"`)
      seen.add(norm(a ?? ''))
    }
  }
}

if (errors.length) {
  console.error(`places.json validation failed (${errors.length}):`)
  for (const e of errors) console.error('  - ' + e)
  process.exit(1)
}

const cmp = (a, b) => a.localeCompare(b, 'en')
const states = [...data.states].sort((a, b) => cmp(a.en, b.en))

// states.js
const statesJs =
  '// Generated by scripts/build-places.mjs from source/places.json. Do not edit by hand.\n' +
  'export const STATES = [\n' +
  states.map((s) => `  { code: ${JSON.stringify(s.code)}, en: ${JSON.stringify(s.en)}, hi: ${JSON.stringify(s.hi)} },`).join('\n') +
  '\n]\n'
fs.writeFileSync(path.join(outDir, 'states.js'), statesJs)

// districts/<CODE>.json
fs.mkdirSync(distDir, { recursive: true })
const wanted = new Set()
for (const s of states) {
  const list = [...s.districts].sort((a, b) => cmp(a.en, b.en)).map((d) => {
    const o = { en: d.en, hi: d.hi }
    if (d.aliases.length) o.aliases = d.aliases
    return o
  })
  const f = `${s.code}.json`
  wanted.add(f)
  fs.writeFileSync(path.join(distDir, f), JSON.stringify(list) + '\n')
}
for (const f of fs.readdirSync(distDir)) if (f.endsWith('.json') && !wanted.has(f)) fs.unlinkSync(path.join(distDir, f))

// supabase/places.sql
const q = (s) => `'${s.replace(/'/g, "''")}'`
const rows = states.flatMap((s) =>
  [...s.districts].sort((a, b) => cmp(a.en, b.en)).map((d) => `  (${q(s.code)}, ${q(s.en)}, ${q(d.en)})`),
)
const sql = `-- GENERATED by scripts/build-places.mjs from src/data/places/source/places.json.
-- Do not edit by hand. Re-run \`node scripts/build-places.mjs\` after changing the source,
-- and apply this file after supabase/schema.sql (it needs the "private" schema to exist).
-- Source: ${data.source.replace(/\n/g, ' ')} (retrieved ${data.retrieved})

begin;

create table if not exists private.places (
  state_code text not null,
  state      text not null,
  district   text not null,
  primary key (state, district)
);

truncate private.places;

insert into private.places (state_code, state, district) values
${rows.join(',\n')};

commit;
`
fs.mkdirSync(path.dirname(sqlFile), { recursive: true })
fs.writeFileSync(sqlFile, sql)

const total = states.reduce((n, s) => n + s.districts.length, 0)
console.log(`ok: ${states.length} states, ${total} districts`)
